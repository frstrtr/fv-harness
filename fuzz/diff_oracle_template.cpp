// diff_oracle_template.cpp — reusable differential fuzzer: production C++ vs the Lean oracle.
//
// Compiled once per target with -DDIFF_ORACLE_BINDING="path/to/binding.hpp". The binding
// header supplies, in namespace `binding`:
//
//   using State = ...; struct Op {...};
//   State initial_state(FuzzedDataProvider&);
//   Op    make_op(FuzzedDataProvider&, const State&);
//   State oracle_step(const State&, const Op&);   // calls the exported Lean functions
//   State impl_step(const State&, const Op&);     // calls the production code
//   bool  same(const State&, const State&);       // bit-exact
//   void  print_state(FILE*, const char* tag, const State&);
//   void  print_op(FILE*, const Op&);
//   void  warm_up();                              // one oracle call on large values
//
// Each input drives a sequence of 1..64 transitions, either fresh operations or one operation
// repeated (saturation run). After every step the oracle's and the implementation's states must
// be identical; the first difference prints both states, writes the input to
// $FV_FUZZ_ARTIFACT_DIR/mismatch-<hash> and exits with status 86. Values come from
// fvfuzz::pick_u64, which favours boundaries: 0, 1, powers of two, 2^63, 2^64-1 and their
// neighbours.

#include <fuzzer/FuzzedDataProvider.h>
#include <sanitizer/lsan_interface.h>

#include <chrono>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <iterator>

namespace fvfuzz {

inline uint64_t pick_u64(FuzzedDataProvider& in) {
  static const uint64_t kEdges[] = {
      0ULL, 1ULL, 2ULL, 3ULL, 9999ULL, 10000ULL, 10001ULL, 0xFFULL, 0x100ULL, 0xFFFFULL,
      0x10000ULL, 0xFFFFFFFFULL, 0x100000000ULL, 0x7FFFFFFFFFFFFFFFULL, 0x8000000000000000ULL,
      0xFFFFFFFFFFFFFFFEULL, 0xFFFFFFFFFFFFFFFFULL};
  const size_t n = std::size(kEdges);
  switch (in.ConsumeIntegralInRange<int>(0, 3)) {
    case 0:
      return kEdges[in.ConsumeIntegralInRange<size_t>(0, n - 1)];
    case 1: {  // a neighbour of an edge, wrapping
      const uint64_t e = kEdges[in.ConsumeIntegralInRange<size_t>(0, n - 1)];
      return e + static_cast<uint64_t>(static_cast<int64_t>(in.ConsumeIntegralInRange<int>(-3, 3)));
    }
    case 2:
      return in.ConsumeIntegralInRange<uint64_t>(0, 1ULL << 20);
    default:
      return in.ConsumeIntegral<uint64_t>();
  }
}

}  // namespace fvfuzz

#include DIFF_ORACLE_BINDING

extern "C" int fv_oracle_init(void);  // generated by LeanOracle.cmake

static const auto kStart = std::chrono::steady_clock::now();

// A mismatch exits with this code after writing the input itself. Going through abort() and
// libFuzzer's deadly-signal path is unreliable once the Lean runtime has installed its own signal
// handlers (observed: ASan CHECK failure and segfault, no reproducer written).
static constexpr int kMismatchExit = 86;

static void write_reproducer(const uint8_t* data, size_t size) {
  const char* dir = std::getenv("FV_FUZZ_ARTIFACT_DIR");
  uint64_t h = 1469598103934665603ULL;  // FNV-1a, names the file by content
  for (size_t i = 0; i < size; ++i) h = (h ^ data[i]) * 1099511628211ULL;
  char path[4096];
  std::snprintf(path, sizeof path, "%s/mismatch-%016llx", dir && *dir ? dir : ".",
                static_cast<unsigned long long>(h));
  if (FILE* f = std::fopen(path, "wb")) {
    std::fwrite(data, 1, size, f);
    std::fclose(f);
    std::fprintf(stderr, "diff-oracle: reproducer written to %s\n", path);
  } else {
    std::fprintf(stderr, "diff-oracle: could not write reproducer to %s\n", path);
  }
}

extern "C" int LLVMFuzzerInitialize(int*, char***) {
  // The Lean runtime builds process-lifetime constants during initialisation (GMP-backed big
  // naturals in Init.Prelude), which LeakSanitizer reports at exit. Only allocations made inside
  // this block are exempt: runtime start, module initializers, and one warm-up oracle call that
  // takes the big-number paths. No suppression pattern is used, so nothing can match production
  // frames; tests/harness_fv_controls checks that a deliberate C++ leak is still reported.
  int rc;
  {
    __lsan::ScopedDisabler lsan_off;
    rc = fv_oracle_init();
    if (rc == 0) binding::warm_up();
  }
  if (rc != 0) {
    std::fprintf(stderr, "diff-oracle: Lean oracle initialisation failed\n");
    std::abort();
  }
  return 0;
}

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
  FuzzedDataProvider in(data, size);
  binding::State s = binding::initial_state(in);
  const int steps = in.ConsumeIntegralInRange<int>(1, 64);
  const bool saturate = in.ConsumeBool();
  const binding::Op repeated = binding::make_op(in, s);
  for (int i = 0; i < steps; ++i) {
    const binding::Op op = saturate ? repeated : binding::make_op(in, s);
    const binding::State want = binding::oracle_step(s, op);
    const binding::State got = binding::impl_step(s, op);
    if (!binding::same(want, got)) {
      const double t =
          std::chrono::duration<double>(std::chrono::steady_clock::now() - kStart).count();
      std::fprintf(stderr, "diff-oracle: MISMATCH at step %d (%.3f s after start)\n", i, t);
      binding::print_state(stderr, "before", s);
      binding::print_op(stderr, op);
      binding::print_state(stderr, "oracle", want);
      binding::print_state(stderr, "impl  ", got);
      write_reproducer(data, size);
      std::fflush(stderr);
      std::_Exit(kMismatchExit);
    }
    s = want;
  }
  return 0;
}
