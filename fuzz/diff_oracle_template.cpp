// diff_oracle_template.cpp — reusable differential fuzzer: production C++ vs the Lean oracle.
//
// Compiled once per target with -DDIFF_ORACLE_BINDING="path/to/binding.hpp". The binding
// header supplies, in namespace `binding`:
//
//   using State = ...; struct Op {...};
//   State initial_state(FuzzedDataProvider&);
//   Op    make_op(FuzzedDataProvider&, const State&);
//   State oracle_step(const State&, const Op&);   // calls the exported Lean functions
//   State impl_step(const State&, const Op&);     // calls the production code
//   bool  same(const State&, const State&);       // bit-exact
//   void  print_state(FILE*, const char* tag, const State&);
//   void  print_op(FILE*, const Op&);
//   void  warm_up();                              // one oracle call on large values
//
// Each input drives a sequence of 1..64 transitions, either fresh operations or one operation
// repeated (saturation run). After every step the oracle's and the implementation's states must
// be identical; the first difference prints both states, writes the input to
// $FV_FUZZ_ARTIFACT_DIR/mismatch-<hash> and exits with status 86. Values come from
// fvfuzz::pick_u64, which favours boundaries: 0, 1, powers of two, 2^63, 2^64-1 and their
// neighbours.
//
// Edge-case classification (labels only, never a verdict) is a SEPARATE BUILD of this file:
// add_diff_fuzzer(<name>) makes the verdict binary <name>, compiled without any classify path, and
// <name>_classify, compiled with -DFV_CLASSIFY_BUILD, which walks each input through the ORACLE
// only and records (FV_CLASSIFY=<log>) or prints (FV_CLASSIFY_RENDER=1) its classes and never
// compares. Nothing at run time (environment, constructors) can switch the verdict binary into a
// no-compare mode, because that code is not in it. fuzz/run_fuzz.sh runs <name>_classify only in
// the replay after the campaign.

