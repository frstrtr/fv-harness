inline uint64_t pick_u64(FuzzedDataProvider& in) {
  static const uint64_t kEdges[] = {
      0ULL, 1ULL, 2ULL, 3ULL, 9999ULL, 10000ULL, 10001ULL, 0xFFULL, 0x100ULL, 0xFFFFULL,
      0x10000ULL, 0xFFFFFFFFULL, 0x100000000ULL, 0x7FFFFFFFFFFFFFFFULL, 0x8000000000000000ULL,
      0xFFFFFFFFFFFFFFFEULL, 0xFFFFFFFFFFFFFFFFULL};
  const size_t n = std::size(kEdges);
  switch (in.ConsumeIntegralInRange<int>(0, 3)) {
    case 0:
      return kEdges[in.ConsumeIntegralInRange<size_t>(0, n - 1)];
    case 1: {  // a neighbour of an edge, wrapping
      const uint64_t e = kEdges[in.ConsumeIntegralInRange<size_t>(0, n - 1)];
      return e + static_cast<uint64_t>(static_cast<int64_t>(in.ConsumeIntegralInRange<int>(-3, 3)));
    }
    case 2:
      return in.ConsumeIntegralInRange<uint64_t>(0, 1ULL << 20);
    default:
      return in.ConsumeIntegral<uint64_t>();
  }
}

